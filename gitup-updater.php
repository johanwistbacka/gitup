<?php
/**
 * GitUp — GitHub-baserade uppdateringar för plugins & teman
 *
 * Översikt
 * --------
 *  - Hookar in i WordPress uppdateringssystem (plugins & teman) och matar in
 *    senaste version från GitHub Releases.
 *  - Hämtar paket via codeload.github.com (zip) och ser till att installationen
 *    landar i rätt mapp (utan att mappnamnet får med taggen).
 *  - Har defensiv loggning till debug.log via `gitup_log()` när WP_DEBUG är true.
 *
 * Prestanda & cache
 * -----------------
 *  - `get_latest_github_release()` cache:ar lyckade taggar i 1h och fel/"N/A" i 5min.
 *  - Core triggar uppdateringscheck via WP-Cron / admin (inte på frontend-sidvisningar).
 *  - Options-sidan kan vara långsammare eftersom den listar releaser; det påverkar inte frontend.
 *
 * Förhandsreleaser
 * ----------------
 *  - Respekteras av både UI och uppdateringsmotorn. Om inställningen är AV används
 *    endast `/releases/latest`. Om PÅ används `/releases?per_page=10` och första icke-draft
 *    plockas (kan vara prerelease).
 */
if (!function_exists('gitup_log')) {
  /**
   * En liten wrapper för att logga till debug.log när WP_DEBUG är på.
   * Används flitigt i uppgraderingsflödena för att förenkla felsökning.
   *
   * @param mixed $msg  Sträng/array/objekt som loggas (array/objekt pretty-printas).
   */
function gitup_log($msg) {
    // Only log if both WP_DEBUG and gitup_debug_mode are enabled
    if (get_option('gitup_debug_mode', '0') !== '1') {
      return;
    }
    if (defined('WP_DEBUG') && WP_DEBUG) {
      if (is_array($msg) || is_object($msg)) {
        $msg = print_r($msg, true);
      }
      error_log('[GitUp] ' . $msg);
    }
  }
}

if (!function_exists('gitup_log_glob_contents')) {
  function gitup_log_glob_contents($label, $path) {
    gitup_log($label . '=' . json_encode(glob(trailingslashit((string) $path) . '*')));
  }
}

if (!function_exists('gitup_log_upgrader_result')) {
  function gitup_log_upgrader_result($label, $result) {
    if (is_wp_error($result)) {
      gitup_log(
        $label .
        ': ERROR code=' . $result->get_error_code()
      );
      return;
    }

    gitup_log($label . ': OK');
  }
}

if (!function_exists('gitup_normalize_version_tag')) {
  function gitup_normalize_version_tag($version) {
    if (!is_string($version)) {
      return $version;
    }
    return ltrim(trim($version), 'vV');
  }
}

if (!function_exists('gitup_github_headers')) {
  function gitup_github_headers() {
    $headers = [
      'User-Agent' => 'WordPress Plugin',
      'Accept'     => 'application/vnd.github+json',
    ];
    $token = get_option('gitup_github_token', '');
    if (!empty($token)) {
      $headers['Authorization'] = 'Bearer ' . $token;
    }
    return $headers;
  }
}

if (!function_exists('gitup_classify_github_request_url')) {
  /**
   * Classify GitHub URLs that GitUp may authenticate.
   *
   * @param mixed $url URL to inspect.
   * @return string `api`, `package`, or an empty string.
   */
  function gitup_classify_github_request_url($url) {
    if (!is_string($url) || $url === '') {
      return '';
    }

    $parts = wp_parse_url($url);
    if (!is_array($parts) || strtolower((string) ($parts['scheme'] ?? '')) !== 'https') {
      return '';
    }
    if (!empty($parts['user']) || !empty($parts['pass']) || (!empty($parts['port']) && (int) $parts['port'] !== 443)) {
      return '';
    }

    $host = strtolower((string) ($parts['host'] ?? ''));
    $path = (string) ($parts['path'] ?? '');
    if ($host === 'api.github.com' && ($path === '/user' || preg_match('#^/repos/[^/]+/[^/]+(?:/|$)#', $path))) {
      return 'api';
    }
    if ($host === 'codeload.github.com' && preg_match('#^/([^/]+)/([^/]+)/zip/refs/tags/([^/]+)$#', $path, $matches)) {
      foreach ([$matches[1], $matches[2]] as $repo_segment) {
        $decoded_segment = rawurldecode($repo_segment);
        if (
          $decoded_segment === '.' ||
          $decoded_segment === '..' ||
          strpos($decoded_segment, '/') !== false ||
          strpos($decoded_segment, '\\') !== false
        ) {
          return '';
        }
      }

      $decoded_tag = rawurldecode($matches[3]);
      foreach (preg_split('#[\\\\/]#', $decoded_tag) ?: [] as $tag_segment) {
        if ($tag_segment === '.' || $tag_segment === '..') {
          return '';
        }
      }
      return 'package';
    }

    return '';
  }
}

if (!function_exists('gitup_register_package_url')) {
  /**
   * Mark a package generated by GitUp for a later upgrader request.
   *
   * @param string $url Package URL.
   * @return void
   */
  function gitup_register_package_url($url) {
    if (gitup_classify_github_request_url($url) !== 'package') {
      return;
    }

    set_transient('gitup_package_' . hash('sha256', $url), '1', DAY_IN_SECONDS);
  }
}

if (!function_exists('gitup_get_package_repo_url')) {
  /**
   * Resolve the canonical GitHub repository for a validated package URL.
   *
   * @param string $url Package URL.
   * @return string
   */
  function gitup_get_package_repo_url($url) {
    if (gitup_classify_github_request_url($url) !== 'package') {
      return '';
    }

    $parts = wp_parse_url($url);
    $segments = explode('/', trim((string) ($parts['path'] ?? ''), '/'));
    if (count($segments) !== 6) {
      return '';
    }

    return gitup_normalize_github_repo_url('https://github.com/' . $segments[0] . '/' . $segments[1]);
  }
}

if (!function_exists('gitup_package_matches_current_update')) {
  /**
   * Check an exact package URL against WordPress' current GitUp update entries.
   *
   * @param string $url Package URL.
   * @return bool
   */
  function gitup_package_matches_current_update($url) {
    $repo_url = gitup_get_package_repo_url($url);
    if ($repo_url === '' || !function_exists('get_site_transient')) {
      return false;
    }

    $plugins = function_exists('get_plugins') ? (array) get_plugins() : [];
    $plugin_updates = get_site_transient('update_plugins');
    if (is_object($plugin_updates) && !empty($plugin_updates->response)) {
      foreach ((array) $plugin_updates->response as $plugin_file => $update) {
        $package = is_object($update) ? ($update->package ?? '') : ($update['package'] ?? '');
        if (
          $package === $url &&
          isset($plugins[$plugin_file]) &&
          gitup_get_plugin_directory($plugin_file) !== '' &&
          gitup_get_plugin_repo_url($plugins[$plugin_file]) === $repo_url
        ) {
          return true;
        }
      }
    }

    $themes = function_exists('wp_get_themes') ? (array) wp_get_themes() : [];
    $theme_updates = get_site_transient('update_themes');
    if (is_object($theme_updates) && !empty($theme_updates->response)) {
      foreach ((array) $theme_updates->response as $stylesheet => $update) {
        $package = is_object($update) ? ($update->package ?? '') : ($update['package'] ?? '');
        if (
          $package === $url &&
          isset($themes[$stylesheet]) &&
          gitup_get_theme_repo_url($themes[$stylesheet]) === $repo_url
        ) {
          return true;
        }
      }
    }

    return false;
  }
}

if (!function_exists('gitup_is_authorized_package_url')) {
  /**
   * Check that GitUp owns the package request before adding credentials.
   *
   * @param string $url Package URL.
   * @return bool
   */
  function gitup_is_authorized_package_url($url) {
    if (gitup_classify_github_request_url($url) !== 'package') {
      return false;
    }

    $registered = get_transient('gitup_package_' . hash('sha256', $url));
    return $registered === '1' || gitup_package_matches_current_update($url);
  }
}

if (!function_exists('gitup_get_plugin_directory')) {
  /**
   * Return a safe directory for a directory-based plugin basename.
   *
   * @param mixed $plugin_basename Plugin basename from WordPress.
   * @return string Empty for root-level or malformed plugin basenames.
   */
  function gitup_get_plugin_directory($plugin_basename) {
    if (!is_string($plugin_basename) || $plugin_basename === '' || trim($plugin_basename) !== $plugin_basename) {
      return '';
    }

    $normalized = str_replace('\\', '/', $plugin_basename);
    if ($normalized === '' || $normalized[0] === '/' || strpos($normalized, '//') !== false) {
      return '';
    }

    $segments = explode('/', $normalized);
    if (count($segments) < 2) {
      return '';
    }
    foreach ($segments as $segment) {
      if ($segment === '' || $segment === '.' || $segment === '..') {
        return '';
      }
    }

    return implode('/', array_slice($segments, 0, -1));
  }
}

if (!function_exists('gitup_normalize_github_repo_url')) {
  function gitup_normalize_github_repo_url($repo_url) {
    if (!is_string($repo_url)) {
      return '';
    }

    $repo_url = trim($repo_url);
    if ($repo_url === '') {
      return '';
    }

    $host = parse_url($repo_url, PHP_URL_HOST);
    if ($host === null) {
      $repo_url = 'https://github.com/' . ltrim($repo_url, '/');
      $host = parse_url($repo_url, PHP_URL_HOST);
    }

    $host = strtolower((string) $host);
    if (!in_array($host, ['github.com', 'www.github.com'], true)) {
      return '';
    }

    $path = (string) parse_url($repo_url, PHP_URL_PATH);
    $path = '/' . trim($path, '/');
    if ($path === '/' || substr_count(trim($path, '/'), '/') < 1) {
      return '';
    }

    return 'https://github.com' . $path;
  }
}

if (!function_exists('gitup_build_github_package_url')) {
  function gitup_build_github_package_url($repo_url, $tag) {
    $repo_url = gitup_normalize_github_repo_url($repo_url);
    if ($repo_url === '' || !is_string($tag) || $tag === '') {
      return '';
    }

    $repo_path = (string) parse_url($repo_url, PHP_URL_PATH);
    if ($repo_path === '') {
      return '';
    }

    $package_url = 'https://codeload.github.com' . $repo_path . '/zip/refs/tags/' . rawurlencode($tag);
    gitup_register_package_url($package_url);
    return $package_url;
  }
}

if (!function_exists('gitup_include_prereleases_enabled')) {
  function gitup_include_prereleases_enabled() {
